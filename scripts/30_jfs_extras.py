"""Generate IJFM extras: highlights and cover letter.

Reuses the graphical abstract generated by 15b_fri_extras.py
(journal-agnostic content).
"""
import json
import os

from docx import Document
from docx.shared import Pt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "manuscript")
os.makedirs(OUT, exist_ok=True)
R = json.load(open(os.path.join(ROOT, "results", "models",
                                "analysis_results.json")))

# ================= HIGHLIGHTS =================
highlights = [
    "Honey antibacterial activity increased monotonically with concentration.",
    "Acidity and osmotic constraints weakened as honey was diluted.",
    "Natural honey exceeded sugar-equivalent controls in most matched pairs.",
    "Catalase-resistant activity suggests non-peroxide effects in tested honeys.",
    "Direct dilution-resolved peroxide measurements remain an evidence gap.",
]
for b in highlights:
    assert len(b) <= 85, (len(b), b)

doc = Document()
doc.styles["Normal"].font.name = "Times New Roman"
doc.styles["Normal"].font.size = Pt(11)
doc.add_heading("Highlights", 1)
doc.add_paragraph("Dilution-dependent antibacterial activity of honey: a "
                  "cross-study quantitative reanalysis of published "
                  "experimental data")
doc.add_paragraph()
for b in highlights:
    doc.add_paragraph(b, style="List Bullet")
# JFS does not use Elsevier-style highlights; files retained for record
# only and are NOT part of the JFS submission package.
doc.save(os.path.join(OUT, "highlights_ijfm.docx"))
with open(os.path.join(OUT, "highlights_ijfm.txt"), "w",
          encoding="utf-8") as f:
    f.write("\n".join("- " + b for b in highlights) + "\n")
print("wrote highlights (record-only)/.txt;", [len(b) for b in highlights])

# ================= COVER LETTER =================
doc = Document()
doc.styles["Normal"].font.name = "Times New Roman"
doc.styles["Normal"].font.size = Pt(11)
import datetime
doc.add_paragraph(datetime.date.today().strftime("%B %d, %Y"))
doc.add_paragraph()
doc.add_paragraph("Dear Editor,")
doc.add_paragraph()
body = [
 "Honey is a food whose resistance to microbial growth is governed by "
 "the same intrinsic factors that food microbiologists use to define "
 "stability in any food ecosystem: water activity, acidity, and "
 "endogenous antimicrobial systems. What makes honey unusual is that it "
 "is almost always evaluated in diluted form, and dilution does not "
 "affect those factors uniformly. Water activity and acidity weaken as "
 "a physicochemical expectation, whereas glucose-oxidase-driven hydrogen peroxide "
 "production is enabled by dilution. Whether the antibacterial activity "
 "of a diluted honey reflects the same mechanism as the concentrated "
 "material is therefore a genuine food-science question, and it is the "
 "question this study examines through quantitative reanalysis.",
 "I submit my manuscript entitled \"Dilution-dependent antibacterial "
 "activity of honey: a cross-study quantitative reanalysis of "
 "published experimental data\" for consideration as "
 "an Original Article in the Journal of Food Science. The manuscript does not "
 "claim a universal mechanistic switch; it reports where the evidence is "
 "strong, where it is thin, and what that distribution means for the "
 "field.",
 "I systematically searched PubMed, Europe PMC and Crossref with "
 "programmatic citation mining and data-repository searches, screened "
 f"{R['selection']['eligible']} eligible primary studies, and extracted "
 f"{R['n_rows']:,} harmonized antibacterial and physicochemical "
 "observations from open-access full texts using a fully documented, "
 "reproducible pipeline. Rather than narrating earlier literature, the "
 "study reconstructs the underlying published measurements, harmonizes "
 "them to common units and concentration bases, and performs new "
 "study-clustered quantitative reanalyses, sensitivity analyses and "
 "cross-study inferences on top of that harmonized corpus. The test "
 "organisms in the corpus are dominated "
 "by bacteria of direct food-safety relevance, including E. coli, "
 "Salmonella, S. aureus, Bacillus and Listeria. The synthesis shows that "
 "antibacterial response was positively associated with concentration "
 "in every extractable series; "
 "that natural honey exceeded sugar-equivalent artificial controls "
 "within every contributing study; that catalase-resistant residual "
 "activity was "
 "substantial where measured; and that within-study "
 "chemistry-outcome associations did not generalize across studies. "
 "Because honey sits at the boundary between a self-preserving food and "
 "a candidate natural antimicrobial ingredient, I believe these results "
 "are of direct interest to the journal's readership in food chemistry, "
 "food microbiology and food preservation.",
 "I report the limits of the evidence with the same prominence as the "
 "positive findings: no extracted study measured activity in an "
 "actual food matrix, catalase experiments came from two "
 "studies, and no extracted dataset measured hydrogen peroxide across a "
 "full dilution ladder with matched antibacterial endpoints. The analysis "
 "quantifies that evidence density explicitly, so readers can see not "
 "only what the literature supports but where it remains too thin to "
 "support stronger claims. All data and code required to regenerate "
 "every reported number and figure are provided as supplementary "
 "material; no proprietary or fabricated data were used.",
 "The manuscript is original, has not been published previously, and is "
 "not under consideration by any other journal. I declare no competing "
 "interests.",
 "I believe this synthesis addresses a question of direct relevance to "
 "food microbiology — how a preserved food's intrinsic antimicrobial "
 "constraints behave across the dilution range in which honey is "
 "actually evaluated — and that its quantified account of evidence "
 "strength provides a sufficiently mature basis for editorial "
 "evaluation, and I respectfully request consideration of the "
 "manuscript for publication in the Journal of Food Science.",
]
for b in body:
    doc.add_paragraph(b)
    doc.add_paragraph()
doc.add_paragraph("Sincerely,")
doc.add_paragraph("Tatsuki Onishi")
doc.add_paragraph("Data Science and AI Innovation Research Promotion "
                  "Center, Shiga University, 1-1-1 Bamba, Hikone, "
                  "Shiga 522-8522, Japan")
doc.add_paragraph("bougtoir@gmail.com; ORCID: 0000-0001-7261-9062")
doc.save(os.path.join(OUT, "cover_letter_jfs.docx"))
print("wrote cover_letter_jfs.docx")
