"""Assemble the Journal of Food Science submission package.

Creates submission/jfs_final/ with:
  - JFS_main_manuscript_FINAL.docx   (standalone copy)
  - JFS_submission_package_FINAL.zip (full package: manuscript files, figures,
    editable tables, data, code, environment files, audits, README)
"""
import json
import os
import shutil
import zipfile

import pandas as pd
from docx import Document
from docx.shared import Pt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FINAL = os.path.join(ROOT, "submission", "jfs_final")
os.makedirs(FINAL, exist_ok=True)

R = json.load(open(os.path.join(ROOT, "results", "models",
                                "analysis_results.json")))


# ---------- package contents ----------
STAGE = os.path.join(FINAL, "pkg_tmp")
if os.path.exists(STAGE):
    shutil.rmtree(STAGE)

files = {
    "manuscript/JFS_main_manuscript.docx": "manuscript/manuscript_jfs.docx",
    "manuscript/JFS_cover_letter.docx": "manuscript/cover_letter_jfs.docx",
    "manuscript/JFS_supplement.docx": "manuscript/supplement_jfs.docx",
    "manuscript/JFS_tables.docx": "manuscript/tables_jfs.docx",
    "README.md": "README.md",
    "environment.yml": "environment.yml",
    "requirements.txt": "requirements.txt",
    "Makefile": "Makefile",
}
# data files needed by the bundled pipeline (canonical layout)
for rel in [
    "data/processed/extraction.csv",
    "data/processed/chemistry.csv",
    "data/processed/studies.csv",
    "data/processed/risk_of_bias.csv",
    "data/processed/extraction_status.csv",
    "data/processed/data_dictionary.md",
    "data/interim/eligible.csv",
    "data/interim/screened.csv",
    "data/interim/manual_extraction.csv",
    "data/interim/auto_outcomes_A.csv",
    "data/interim/auto_chem_B.csv",
    "data/interim/auto_series_C.csv",
    "data/interim/table_catalog.csv",
    "data/interim/crossref_cache.json",
    "data/interim/fulltext_manifest.csv",
    "logs/search_log.csv",
    "logs/repo_search_log.csv",
    "logs/prisma_counts.json",
    "logs/pmcid_resolution.json",
    "references/references_fri.csv",
    "references/references_context.csv",
    "references/references_fri_context.csv",
    "results/models/analysis_results.json",
    "results/models/v4_analysis.json",
    "results/models/v5_analysis.json",
]:
    files[rel] = rel
for arc, rel in files.items():
    src = os.path.join(ROOT, rel)
    if os.path.exists(src):
        dst = os.path.join(STAGE, arc)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
    else:
        print("MISSING", rel)

# figures (PNG + TIFF + SVG) — regenerated by `make figures`, also shipped
for f in os.listdir(os.path.join(ROOT, "results", "figures")):
    if f.endswith((".png", ".tiff", ".svg")):
        dst = os.path.join(STAGE, "results", "figures", f)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(os.path.join(ROOT, "results", "figures", f), dst)

# per-analysis result tables
for f in os.listdir(os.path.join(ROOT, "results", "tables")):
    dst = os.path.join(STAGE, "results", "tables", f)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(os.path.join(ROOT, "results", "tables", f), dst)

# canonical pipeline scripts (FRI/IJFM-era legacy generators excluded)
CANON = """00_search 00b_citation_mining 00c_repo_search 01_screen
02_rank_candidates 03b_resolve_pmcid 03_fetch_pmc 04_eligibility
05_parse_tables 06_autoextract 07_manual_extraction 08_build_dataset
09_dictionary_rob 10_analyze 10b_analyze_fri 11_figures
12b_references_fri 16b_qc_fri 18_extraction_bias 21_gate2_rescue
22_three_line_tables 23_provenance_cleanup 24_v4_gates 25_v5_gates
27_jfs_cleanup 28_manuscript_jfs 29_supplement_jfs 30_jfs_extras
31_tables_standalone_jfs 32_package_jfs 33_three_line_jfs
34_regression_output_dirs""".split()
for f in CANON:
    src = os.path.join(ROOT, "scripts", f + ".py")
    dst = os.path.join(STAGE, "scripts", f + ".py")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)

# Internal QC audits are excluded from the submission package (editorial
# material only); they remain versioned in the repository.

# ---------- zip ----------
zpath = os.path.join(FINAL, "JFS_submission_package_FINAL.zip")
if os.path.exists(zpath):
    os.remove(zpath)
with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
    for dirpath, _, fns in os.walk(STAGE):
        for fn in fns:
            fp = os.path.join(dirpath, fn)
            z.write(fp, os.path.relpath(fp, STAGE))

# standalone FINAL copies
for _src, _dst in [("manuscript_jfs.docx", "JFS_main_manuscript_FINAL.docx"),
                   ("cover_letter_jfs.docx", "JFS_cover_letter_FINAL.docx"),
                   ("supplement_jfs.docx", "JFS_supplement_FINAL.docx"),
                   ("tables_jfs.docx", "JFS_tables_FINAL.docx")]:
    shutil.copy2(os.path.join(ROOT, "manuscript", _src),
                 os.path.join(FINAL, _dst))

n = len(zipfile.ZipFile(zpath).namelist())
sz = os.path.getsize(zpath) / 1e6
msz = os.path.getsize(os.path.join(FINAL, "JFS_main_manuscript_FINAL.docx")) / 1e6
print(f"wrote {zpath} ({n} files, {sz:.1f} MB)")
print(f"wrote JFS_main_manuscript_FINAL.docx ({msz:.1f} MB)")
shutil.rmtree(STAGE)
